#include <iostream>
using namespace std;

int main() {
    
    for (int i = 1; i <= 5; i++) {        // For loop to print numbers 1 to 5
        cout << "Number: " << i << endl;  // Output each number
    }

    return 0;
}

/*
Explanation:

1. Uses a for loop to iterate from 1 to 5
2. Prints each number with the label "Number:"

Output:
Number: 1  
Number: 2  
Number: 3  
Number: 4  
Number: 5
*/
